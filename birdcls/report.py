"""Generate a detailed Markdown record ("run card") for every completed run.

    python -m birdcls.report
    python -m birdcls.report --compare RUN [RUN ...] --labels S0 S1 --out track1_S0_vs_S1

Writes experiments/runs/<run>.md for each complete run in outputs/runs/ plus experiments/runs/INDEX.md.
Every number is read from the run's saved files (history.json, config.yaml, best.pt metadata) and from
outputs/results.csv, so the records always match the evidence on disk. Re-run after training or evaluating.
The hand-written experiment notes (experiments/EXP-*.md) link to these cards.
"""
import argparse
import datetime as dt

import pandas as pd
import torch
import yaml

from . import config as C
from .plots import plot_run_comparison
from .utils import load_json

CARDS_DIR = C.ROOT / "experiments" / "runs"


def load_run_config(name, hist):
    """The configuration snapshot saved with the run; older runs (trained in the notebook) have none,
    so the current configs/<name>.yaml is used and the card says so."""
    snap = C.run_dir(name) / "config.yaml"
    if snap.exists():
        with open(snap) as f:
            return yaml.safe_load(f), "snapshot saved with the run (`config.yaml`)"
    cfg = C.load_config(hist["config"]).to_dict()
    cfg["model"] = hist["model"]
    return cfg, (f"no snapshot (trained with the original notebook); values from `configs/{hist['config']}.yaml`, "
                 "which matches the notebook settings")


def card(name, results):
    d = C.run_dir(name)
    hist = load_json(d / "history.json")
    cfg, cfg_source = load_run_config(name, hist)
    ckpt = torch.load(d / "best.pt", map_location="cpu", weights_only=True)
    n_params = sum(v.numel() for k, v in ckpt["state_dict"].items()
                   if not k.endswith(("running_mean", "running_var", "num_batches_tracked")))
    finished = dt.datetime.fromtimestamp((d / "history.json").stat().st_mtime).strftime("%Y-%m-%d %H:%M")
    n_epochs = len(hist["val_acc"])
    planned = sum(p["epochs"] for p in cfg["phases"])
    stopped = "completed all epochs" if n_epochs >= planned else f"early stopping after {n_epochs}/{planned} epochs"
    notebook_run = not (d / "config.yaml").exists()
    if notebook_run:   # migrated from the original notebook: the file date is the migration date
        finished += " (file date of the migration; trained earlier the same day in the notebook)"
        command = "original notebook, `archive/notebook_convnext_tiny_run.ipynb` (same training logic as `birdcls`)"
    else:
        command = f"`python -m birdcls.train --model {hist['model']} --config {hist['config']}`"

    L = [f"# Run card: `{name}`", "",
         "_Generated by `python -m birdcls.report` from the files in "
         f"`outputs/runs/{name}/`. Do not edit by hand._", "",
         "## Summary", "",
         "| Item | Value |", "|---|---|",
         f"| Model | `{hist['model']}` ({n_params / 1e6:.2f} M parameters) |",
         f"| Configuration | `{hist['config']}`: {cfg.get('description', '')} |",
         f"| Finished | {finished} |",
         f"| Training time | {hist['minutes']:.1f} min, {stopped} |",
         (f"| Checkpoint | **final epoch {hist['best_epoch'] + 1}** (full-train: trained on train + val, "
          "no validation, no early stopping) |" if hist.get("full_train") else
          f"| Best epoch (by val accuracy) | {hist['best_epoch'] + 1} at {hist['best_img_size']} px, "
          f"val Top-1 {hist['best_val_acc']:.4f} |"),
         f"| Input normalisation | mean {tuple(ckpt.get('mean', C.MEAN))}, std {tuple(ckpt.get('std', C.STD))} |",
         f"| Command | {command} |",
         ""]

    rows = results[results.index.str.replace(" +TTA", "", regex=False) == name] if results is not None else None
    L += ["## Results (from `outputs/results.csv`)", ""]
    if rows is not None and len(rows):
        cols = ["train_acc", "val_top1", "gap", "test_top1", "test_avg_per_class"]
        L += ["| Variant | Train acc (clean) | Val Top-1 | Gap (train - val) | **Test Top-1** | **Test avg/class** |",
              "|---|---|---|---|---|---|"]
        for idx, r in rows.iterrows():
            variant = "with TTA (flip averaging)" if r["tta"] else "no TTA"
            L.append(f"| {variant} | " + " | ".join(f"{r[c]:.4f}" for c in cols) + " |")
        L += ["", "Train acc is measured on the training images with eval preprocessing (no augmentation)."]
    else:
        L.append("_Not evaluated yet: run `python -m birdcls.evaluate --runs " + name + "`._")
    L.append("")

    L += ["## Configuration", "", f"Source: {cfg_source}.", "", "| Setting | Value |", "|---|---|"]
    for k, v in cfg.items():
        if k not in ("phases", "name", "description", "model"):
            L.append(f"| `{k}` | {v} |")
    L += ["", "| Phase | Image size | Batch | Epochs | LR backbone | LR head | Warm-up epochs |",
          "|---|---|---|---|---|---|---|"]
    for i, p in enumerate(cfg["phases"], 1):
        L.append(f"| {i} | {p['img_size']} | {p['batch_size']} | {p['epochs']} | {p['lr_backbone']:g} | "
                 f"{p['lr_head']:g} | {p.get('warmup_epochs', 0)} |")
    L.append("")

    L += ["## Training curves", "", f"![curves](../../outputs/runs/{name}/curves.png)", "",
          "## Per-epoch log", "",
          "| Epoch | Phase | Size | Train loss | Train acc | Val loss | Val acc | LR (backbone, end of epoch) |",
          "|---|---|---|---|---|---|---|---|"]
    starts = hist["phase_starts"] + [n_epochs]
    lrs = hist.get("lr_backbone", [None] * n_epochs)
    for e in range(n_epochs):
        phase = max(i for i, s in enumerate(starts[:-1]) if s <= e) + 1
        best = " **(best)**" if e == hist["best_epoch"] else ""
        lr = f"{lrs[e]:.2e}" if lrs[e] is not None else "n/a"
        L.append(f"| {e + 1}{best} | {phase} | {hist['img_size'][e]} | {hist['train_loss'][e]:.3f} | "
                 f"{hist['train_acc'][e]:.3f} | {hist['val_loss'][e]:.3f} | {hist['val_acc'][e]:.4f} | {lr} |")
    L += ["", "With CutMix, train loss/acc are computed on mixed images (soft accuracy), so they run lower than "
          "the clean train accuracy in the results table.", "",
          "## Files", "",
          f"`outputs/runs/{name}/`: `best.pt` (best checkpoint), `history.json`, `train.log`, `curves.png`"
          + (", `config.yaml`" if (d / "config.yaml").exists() else ""), ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--compare", nargs="+", help="also draw a comparison figure of these runs")
    ap.add_argument("--labels", nargs="+", help="short labels for --compare (default: run names)")
    ap.add_argument("--out", help="figure name for --compare, saved to outputs/figures/<out>.png")
    args = ap.parse_args()
    if args.compare:
        C.FIGURES_DIR.mkdir(parents=True, exist_ok=True)
        path = C.FIGURES_DIR / f"{args.out or '_vs_'.join(args.compare)}.png"
        plot_run_comparison({n: load_json(C.run_dir(n) / "history.json") for n in args.compare}, path, args.labels)
        print(f"wrote {path}")

    CARDS_DIR.mkdir(parents=True, exist_ok=True)
    csv = C.OUTPUT_DIR / "results.csv"
    results = pd.read_csv(csv, index_col="run") if csv.exists() else None
    names = [n for n in C.completed_runs() if not n.endswith("__smoke")]

    index = ["# Run index", "", "_Generated by `python -m birdcls.report`._", "",
             "| Run | Model | Config | Best epoch | Val Top-1 (training log) | Test Top-1 | Test avg/class | Time (min) |",
             "|---|---|---|---|---|---|---|---|"]
    for name in names:
        (CARDS_DIR / f"{name}.md").write_text(card(name, results))
        hist = load_json(C.run_dir(name) / "history.json")
        r = results.loc[name] if results is not None and name in results.index else None
        test = f"{r['test_top1']:.4f}" if r is not None else "-"
        avg = f"{r['test_avg_per_class']:.4f}" if r is not None else "-"
        index.append(f"| [{name}]({name}.md) | `{hist['model']}` | `{hist['config']}` | {hist['best_epoch'] + 1} | "
                     f"{hist['best_val_acc']:.4f} | {test} | {avg} | {hist['minutes']:.1f} |")
    index += ["", "Test columns are without TTA; TTA variants are in each run card. Val Top-1 here is the value logged "
              "during training; `evaluate` re-measures it and can differ by about 1 image (float16 numerics)."]
    (CARDS_DIR / "INDEX.md").write_text("\n".join(index) + "\n")
    print(f"wrote {len(names)} run cards + INDEX.md to {CARDS_DIR}")


if __name__ == "__main__":
    main()
